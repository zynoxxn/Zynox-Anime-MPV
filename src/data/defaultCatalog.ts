function generateEpisodes(
  animeId: string,
  animeTitle: string,
  epCount: number,
  thumbUrl: string,
  episodeTitles: string[],
  seasonAssigner?: (epNum: number) => { seasonNumber: number; thumbnail?: string }
): Episode[] {
  return Array.from({ length: epCount }, (_, i) => {
    const epNum = i + 1;
    const titleStr = episodeTitles[i] || `Episode ${epNum}`;
    const videoUrl = sampleVideoUrls[i % sampleVideoUrls.length];
    const seasonInfo = seasonAssigner ? seasonAssigner(epNum) : { seasonNumber: 1, thumbnail: thumbUrl };
    const epSeasonNum = seasonInfo.seasonNumber || 1;
    const epThumbnail = seasonInfo.thumbnail || thumbUrl;

    return {
      id: `ep-${animeId}-${epNum}`,
      animeId,
      episodeNumber: epNum,
      seasonNumber: epSeasonNum,
      season: epSeasonNum,
      title: titleStr,
      description: `${animeTitle} - Episode ${epNum}. High-speed Hindi Dub and Multi-Audio streaming in 1080p Ultra HD.`,
      thumbnail: epThumbnail,
      language: 'DUB',
      quality: '1080p',
      viewsCount: 15000 + (epCount - epNum) * 2300,
      published: true,
      duration: '24:00',
      videoUrl: videoUrl,
      downloadUrl: `https://mega.nz/file/${animeId}-ep${epNum}`,
      downloadQuality: '1080p Ultra HD',
      downloadSize: '320 MB',
      sources: [
        {
          id: `src-${epNum}-1`,
          provider: 'Fast Stream 1 [Hindi Dub]',
          sourceName: 'Server 1 (Direct HD)',
          type: 'mp4',
          quality: '1080p Ultra HD',
          language: 'DUB',
          embedUrl: videoUrl,
          active: true,
        },
      ],
    };
  });
}

